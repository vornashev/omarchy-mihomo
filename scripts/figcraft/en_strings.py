def en(s):
    if s in EXACT:
        return EXACT[s]
    out = s
    for ru, e in UNITS:
        out = re.sub(r"(?<=\d) ?" + ru + r"\b", " " + e, out)
    return out


def untranslated(s):
    return bool(CYR.search(en(s)))
